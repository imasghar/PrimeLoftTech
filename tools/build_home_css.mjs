import fs from 'node:fs';
import crypto from 'node:crypto';
import { createRequire } from 'node:module';
const require = createRequire(new URL('./css-build/package.json', import.meta.url));
const CleanCSS = require('clean-css');
const sources = JSON.parse(fs.readFileSync(new URL('./css-build/home-sources.json', import.meta.url), 'utf8').replace(/^\uFEFF/, ''));
const source = sources.map(path => fs.readFileSync(path, 'utf8')).join('\n');
// Level 1 normalizes values/whitespace; no level 2 merging or unused-rule removal.
const result = new CleanCSS({level:{1:{selectorsSortingMethod:'none',roundingPrecision:false}},rebase:false}).minify(source);
if (result.errors.length || result.warnings.length) throw new Error([...result.errors,...result.warnings].join('\n'));
const hash = crypto.createHash('sha256').update(source).digest('hex').slice(0,12);
fs.writeFileSync('css/home.bundle.min.css',`/* Generated by node tools/build_home_css.mjs; source hash ${hash}. */\n${result.styles}\n`);
let html = fs.readFileSync('index.html','utf8');
html=html.replace(/css\/home\.bundle\.min\.css\?v=[a-z0-9.]+/g,`css/home.bundle.min.css?v=${hash}`);
fs.writeFileSync('index.html',html);
console.log(JSON.stringify({sources,inputBytes:Buffer.byteLength(source),outputBytes:Buffer.byteLength(result.styles),hash}));
