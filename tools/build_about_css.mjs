import fs from 'node:fs';
import crypto from 'node:crypto';
import { createRequire } from 'node:module';
const require = createRequire(new URL('./css-build/package.json', import.meta.url));
const CleanCSS = require('clean-css');
// Preserve the existing cascade; level 0 changes formatting only.
const sources = JSON.parse(fs.readFileSync(new URL('./css-build/about-sources.json', import.meta.url), 'utf8')); 
const source = sources.map(path => fs.readFileSync(path, 'utf8')).join('\n');
const result = new CleanCSS({level:0,rebase:false}).minify(source);
if (result.errors.length) throw new Error(result.errors.join('\n'));
if (result.warnings.length) throw new Error(result.warnings.join('\n'));
const hash = crypto.createHash('sha256').update(source).digest('hex').slice(0,12);
const output = `/* Generated by node tools/build_about_css.mjs; source hash ${hash}. */\n${result.styles}\n`;
fs.writeFileSync('css/about.bundle.min.css',output);
let html = fs.readFileSync('about.html','utf8');
html = html.replace(/css\/about\.bundle\.min\.css\?v=[a-z0-9.]+/g, `css/about.bundle.min.css?v=${hash}`);
fs.writeFileSync('about.html', html);
console.log(JSON.stringify({sources,inputBytes:Buffer.byteLength(source),outputBytes:Buffer.byteLength(output),hash}));
